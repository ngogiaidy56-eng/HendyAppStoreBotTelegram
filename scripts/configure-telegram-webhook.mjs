const token=String(process.env.BOT_TOKEN||'').trim();
const secret=String(process.env.BOT_WEBHOOK_SECRET||'').trim();
const base=String(process.env.TELEGRAM_BOT_WORKER_URL||'').trim().replace(/\/+$/,'');
if(!token)throw new Error('BOT_TOKEN GitHub Actions secret is required.');
if(!secret)throw new Error('BOT_WEBHOOK_SECRET GitHub Actions secret is required.');
if(!base)throw new Error('TELEGRAM_BOT_WORKER_URL is required.');
if(!/^[A-Za-z0-9_-]{1,256}$/.test(secret))throw new Error('BOT_WEBHOOK_SECRET must use only letters, numbers, underscores and hyphens.');
const url=base+'/telegram/webhook';
const response=await fetch('https://api.telegram.org/bot'+token+'/setWebhook',{method:'POST',headers:{'content-type':'application/json'},body:JSON.stringify({url,secret_token:secret,allowed_updates:['message','callback_query'],drop_pending_updates:false})});
const result=await response.json().catch(()=>({}));
if(!response.ok||result.ok!==true)throw new Error('Telegram setWebhook failed ('+response.status+'): '+String(result.description||'Telegram returned an unsuccessful response.'));
console.log('Telegram webhook configured at '+url);
